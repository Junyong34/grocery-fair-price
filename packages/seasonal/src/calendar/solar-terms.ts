const SERIES = [L0, L1, L2, L3, L4, L5]

const DAY_MS = 86_400_000
const UNIX_EPOCH_JD = 2440587.5
const J2000 = 2451545
const TROPICAL_YEAR = 365.2422
const rad = (degrees: number) => (degrees * Math.PI) / 180
const normalize = (degrees: number) => ((degrees % 360) + 360) % 360

/** TT와 UT의 차(초). Espenak·Meeus 다항식. 몇 초 틀려도 날짜에는 영향이 없다. */
function deltaT(year: number): number {
  if (year < 2005) {
    const t = year - 2000
    return 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5
  }
  if (year < 2050) {
    const t = year - 2000
    return 62.92 + 0.32217 * t + 0.005589 * t ** 2
  }
  const u = (year - 1820) / 100
  return -20 + 32 * u ** 2 - 0.5628 * (2150 - year)
}

/** 그 순간(JDE, 역학시) 태양의 겉보기 황경(도). */
function apparentSolarLongitude(jde: number): number {
  const tau = (jde - J2000) / 365250
  const heliocentric = SERIES.reduce(
    (sum, series, power) =>
      sum + series.reduce((part, [a, b, c]) => part + a * Math.cos(b + c * tau), 0) * tau ** power,
    0
  ) / 1e8
  const t = tau * 10
  const geometric = normalize((heliocentric * 180) / Math.PI + 180) - 0.09033 / 3600
  // 장동(ch.22 주요 항)
  const omega = rad(125.04452 - 1934.136261 * t)
  const sunMean = rad(280.4665 + 36000.7698 * t)
  const moonMean = rad(218.3165 + 481267.8813 * t)
  const nutation =
    (-17.2 * Math.sin(omega) - 1.32 * Math.sin(2 * sunMean) - 0.23 * Math.sin(2 * moonMean) + 0.21 * Math.sin(2 * omega)) / 3600
  // 광행차(ch.25). 지구-태양 거리 R은 근사식으로 충분하다.
  const anomaly = rad(357.52911 + 35999.05029 * t)
  const distance = 1.000140 - 0.016708 * Math.cos(anomaly) - 0.000139 * Math.cos(2 * anomaly)
  const aberration = -20.4898 / 3600 / distance
  return normalize(geometric + nutation + aberration)
}

/**
 * 그 양력 연도 안에서 태양 황경이 longitude°(0~359, 15의 배수가 절기)가 되는 순간(UTC 밀리초).
 * 소한(285°)·대한(300°)은 1월이라 그해 1월의 순간을 돌려준다.
 */
export function solarTermInstant(year: number, longitude: number): number {
  const target = normalize(longitude)
  // 춘분(3월 20일 무렵)에서 하루 약 1°씩 간다. 동지(270°) 뒤의 절기는 그해 1~3월이다.
  const offset = target > 270 ? target - 360 : target
  let jde = (Date.UTC(year, 2, 20) / DAY_MS + UNIX_EPOCH_JD) + (offset * TROPICAL_YEAR) / 360
  for (let i = 0; i < 20; i++) {
    const diff = ((target - apparentSolarLongitude(jde) + 540) % 360) - 180
    jde += (diff * TROPICAL_YEAR) / 360
    if (Math.abs(diff) < 1e-7) break
  }
  return (jde - UNIX_EPOCH_JD) * DAY_MS - deltaT(year) * 1000
}

/** 그 양력 연도의 절기(황경 longitude°)가 드는 서울 날짜. */
export function solarTermDate(year: number, longitude: number): CalendarDate {
  const seoul = new TZDate(solarTermInstant(year, longitude), TIME_ZONE)
  return { year: seoul.getFullYear(), month: seoul.getMonth() + 1, day: seoul.getDate() }
}
